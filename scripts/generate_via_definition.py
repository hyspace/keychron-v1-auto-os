#!/usr/bin/env python3
"""Build a VIA v3 definition from the official layout and current RGB effect order."""

import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
QMK = ROOT / "qmk_firmware"
KEYMAP = ROOT / "keyboards/keychron/v1/ansi_encoder/keymaps/auto_os"
VERSION = (ROOT / "VERSION").read_text().strip()
DEST = ROOT / f"via/keychron-v1-auto-os-v{VERSION}.json"


def main():
    definition = json.loads((ROOT / "data/keychron-v1-official-via.json").read_text())
    assert (definition["vendorId"], definition["productId"]) == ("0x3434", "0x0311")
    assert len(definition["customKeycodes"]) == 11
    info = json.loads((QMK / "keyboards/keychron/v1/info.json").read_text())
    enabled = [name.upper() for name, value in info["rgb_matrix"]["animations"].items() if value]
    source = "\n".join(f"#define ENABLE_RGB_MATRIX_{name}" for name in enabled)
    source += '\n#define RGB_MATRIX_FRAMEBUFFER_EFFECTS\n#define RGB_MATRIX_KEYREACTIVE_ENABLED\n'
    source += '#define RGB_MATRIX_EFFECT(name, ...) VIA_EFFECT(name)\n#include "rgb_matrix_effects.inc"\n'
    processed = subprocess.check_output([
        "clang", "-E", "-P", "-x", "c", "-I", str(QMK / "quantum/rgb_matrix/animations"), "-",
    ], input=source, text=True)
    effects = ["NONE", *re.findall(r"VIA_EFFECT\((\w+)\)", processed)]
    assert set(effects) == {"NONE", "SOLID_COLOR", *enabled}
    options = [[f"{i:02d}. {name}", i] for i, name in enumerate(effects)]
    controls = definition["menus"][0]["content"][0]["content"]
    next(c for c in controls if c.get("label") == "Effect")["options"] = options
    definition["name"] = f"Keychron V1 ANSI Knob - Auto OS {VERSION}"
    config = (KEYMAP / "config.h").read_text()
    version = int(re.search(r"#define VIA_FIRMWARE_VERSION (0x[0-9A-Fa-f]+)", config)[1], 16)
    assert version == int("".join(f"{int(v):02x}" for v in VERSION.split(".")), 16), "VERSION/config.h mismatch"
    definition["firmwareVersion"] = version
    definition["keycodes"] = ["qmk_rgb_matrix_keycodes"]
    definition["customKeycodes"][6]["title"] = "Keychron Siri shortcut: hold Command+Space for 500 ms; requires matching macOS setting"
    definition["customKeycodes"][10]["title"] = "Legacy Cortana shortcut: Win+C; behavior depends on Windows version"
    DEST.parent.mkdir(exist_ok=True)
    DEST.write_text(json.dumps(definition, indent=2) + "\n")
    checks = ["// Generated by scripts/generate_via_definition.py.",
              "// Fail compilation if the VIA menu diverges from the real firmware enum.",
              "#pragma once"]
    checks += [f'_Static_assert(RGB_MATRIX_{name} == {i}, "VIA RGB effect ID: {name}");'
               for i, name in enumerate(effects)]
    checks += [f'_Static_assert(RGB_MATRIX_EFFECT_MAX == {len(effects)}, "VIA effect count");',
               f'_Static_assert(VIA_FIRMWARE_VERSION == {version}, "VIA firmware version");']
    (KEYMAP / "via_effects_check.h").write_text("\n".join(checks) + "\n")
    print(f"Generated {DEST}: 11 custom keys, {len(effects)} lighting selections")


if __name__ == "__main__":
    main()
