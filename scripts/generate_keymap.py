#!/usr/bin/env python3
"""Historical migration helper: emit a legacy-layout conversion to work/, not live source."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BACKUP = ROOT / "tests/fixtures/legacy-keymap.json"
DEST = ROOT / "work/migrated-keymap.c"

SPECIAL = {
    0x5221: "MO(MAC_FN)", 0x5223: "MO(WIN_FN)", 0x7013: "NK_TOGG",
}
CUSTOM_NAMES = [
    "KCH_MISSION_CONTROL", "KCH_LAUNCHPAD", "KCH_LEFT_OPTION", "KCH_RIGHT_OPTION",
    "KCH_LEFT_COMMAND", "KCH_RIGHT_COMMAND", "KCH_SIRI", "KCH_TASK_VIEW",
    "KCH_FILE_EXPLORER", "KCH_SCREENSHOT", "KCH_CORTANA",
]
SPECIAL.update(dict(enumerate(CUSTOM_NAMES, start=0x7F00)))
SPECIAL.update(dict(enumerate([
    "RM_TOGG", "RM_NEXT", "RM_PREV", "RM_HUEU", "RM_HUED", "RM_SATU",
    "RM_SATD", "RM_VALU", "RM_VALD", "RM_SPDU", "RM_SPDD",
], start=0x7820)))


def translate(code):
    if code in SPECIAL:
        return SPECIAL[code]
    if 0 <= code <= 0xFF:
        return f"0x{code:04X}"
    raise ValueError(f"Unreviewed legacy keycode: {code:#06x}")


def main():
    backup = json.loads(BACKUP.read_text())
    assert (backup["layers"], backup["rows"], backup["cols"]) == (4, 6, 16)
    assert backup["via_protocol"] == 11
    data = bytes.fromhex(backup["keymap_hex"])
    assert len(data) == 4 * 6 * 16 * 2
    codes = [int.from_bytes(data[i:i + 2], "big") for i in range(0, len(data), 2)]
    layers = ["MAC_BASE", "MAC_FN", "WIN_BASE", "WIN_FN"]
    lines = [
        "// SPDX-License-Identifier: GPL-2.0-or-later",
        "// Generated by scripts/generate_keymap.py from the verified pre-flash backup.",
        '#include QMK_KEYBOARD_H', '#include "auto_os.h"',
        '#include "keychron_compat.h"', '#include "via_effects_check.h"', "",
        "const uint16_t PROGMEM keymaps[][MATRIX_ROWS][MATRIX_COLS] = {",
    ]
    for layer, name in enumerate(layers):
        lines.append(f"    [{name}] = {{")
        for row in range(6):
            start = (layer * 6 + row) * 16
            lines.append("        {" + ", ".join(translate(v) for v in codes[start:start + 16]) + "},")
        lines.append("    },")
    lines.extend(["};", "", "const uint16_t PROGMEM encoder_map[][NUM_ENCODERS][NUM_DIRECTIONS] = {"])
    for name, (ccw, cw) in zip(layers, backup["encoders_ccw_cw"], strict=True):
        lines.append(f"    [{name}] = {{ENCODER_CCW_CW({translate(ccw)}, {translate(cw)})}},")
    lines.extend(["};", ""])
    DEST.parent.mkdir(exist_ok=True)
    DEST.write_text("\n".join(lines))
    print(f"Generated {DEST}")


if __name__ == "__main__":
    main()
